let sequence = 0;

function routineExercise(
  exerciseId: string,
  sets: number,
  repsMin: number,
  repsMax: number,
  restSeconds: number,
  notes = "",
): RoutineExercise {
  sequence += 1;
  return {
    id: `re-${sequence}`,
    exerciseId,
    order: sequence,
    sets,
    repsMin,
    repsMax,
    restSeconds,
    notes,
  };
}

function day(id: string, name: string, order: number, exercises: RoutineExercise[]): RoutineDay {
  return { id, name, order, exercises: exercises.map((exercise, index) => ({ ...exercise, order: index + 1 })) };
}

