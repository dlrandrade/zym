function createCompletedWorkout(index: number, date: string, goal: Goal = "hipertrofia"): Workout {
  const progressiveWeight = 48 + index * 2;
  return {
    id: `workout-history-${index}`,
    name: index % 3 === 0 ? "Treino A" : index % 3 === 1 ? "Treino B" : "Treino C",
    routineId: "demo-routine",
    routineDayId: templateBase.days[index % 3].id,
    startedAt: `${date}T18:10:00.000Z`,
    endedAt: `${date}T19:02:00.000Z`,
    durationSeconds: 3120 + index * 45,
    status: "completed",
    notes: goal === "forca" ? "Boa velocidade nas séries principais." : "Execução consistente.",
    exercises: [
      {
        id: `we-${index}-1`,
        exerciseId: "ex-bench",
        order: 1,
        restSeconds: 120,
        sets: [0, 1, 2].map((setIndex) => ({
          id: `ws-${index}-bench-${setIndex}`,
          setNumber: setIndex + 1,
          type: "normal",
          weight: progressiveWeight + setIndex * 2,
          reps: 10 - setIndex,
          rpe: 7 + setIndex * 0.5,
          completed: true,
          completedAt: `${date}T18:${20 + setIndex * 4}:00.000Z`,
        })),
      },
      {
        id: `we-${index}-2`,
        exerciseId: "ex-row",
        order: 2,
        restSeconds: 105,
        sets: [0, 1, 2].map((setIndex) => ({
          id: `ws-${index}-row-${setIndex}`,
          setNumber: setIndex + 1,
          type: "normal",
          weight: progressiveWeight - 4 + setIndex * 2,
          reps: 10,
          rpe: 7.5,
          completed: true,
          completedAt: `${date}T18:${38 + setIndex * 4}:00.000Z`,
        })),
      },
    ],
  };
}

